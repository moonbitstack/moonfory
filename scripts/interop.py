"""Write the Python half of the interop fixtures.

Run this by hand, with `pyfory` installed, from the module root:

    python3 scripts/interop.py

It writes `src/fixtures_pyfory_test.mbt`: one entry per class of message, holding the
bytes `pyfory` wrote for a value of that class. The file is checked in, and the
tests read it; CI never runs this script and never needs Python, which is what
makes a byte-level interop test affordable on every push.

The bytes are the whole fixture. Nothing here says what the value *is* — the
MoonBit side decodes them and says so — so a fixture cannot be "fixed" by
changing both sides at once: the only way to make a failing fixture pass is to
read the bytes the way the peer that wrote them meant them.
"""

import datetime
import decimal
import enum
import pathlib
import sys

import pyfory
from dataclasses import dataclass
from typing import Dict, List, Optional


class Color(enum.IntEnum):
    RED = 0
    GREEN = 1


@dataclass
class Point:
    x: pyfory.Int32
    y: pyfory.Int32


@dataclass
class Person:
    name: str
    age: pyfory.Int32
    tags: List[str]
    home: Optional[Point]


def cases():
    """Every message class the format defines, and a value of each.

    The order is the order of the file the tests read, so it is kept stable by
    hand rather than sorted: a diff that reorders the fixtures is a diff nobody
    can read.
    """
    point = Point(1, 2)
    person = Person("ann", 30, ["x", "y"], Point(3, 4))
    return [
        # The scalars: one of each width the type mapping carries.
        ("bool", True),
        ("int32", 42),
        ("uint8", 200),
        ("float64", 1.5),
        # A string in each of the three encodings the format allows.
        ("string_latin1", "ab"),
        ("string_utf8", "世界"),
        ("string_empty", ""),
        # Bytes, which are not a string: the same six characters on the wire as
        # `"ab"`, in a different type.
        ("binary", b"ab"),
        # Containers.
        ("list_int", [1, 2, 3]),
        ("list_str", ["a", "b"]),
        ("list_empty", []),
        ("set_int", {1, 2}),
        ("map_str_int", {"a": 1}),
        # The dense arrays: a run of raw elements rather than a list of values.
        ("int32_array", pyfory.Int32Array([1, 2, 3])),
        ("float64_array", pyfory.Float64Array([1.5, 2.5])),
        # Decimal, and the three time types.
        ("decimal", decimal.Decimal("123.45")),
        (
            "timestamp",
            datetime.datetime(1970, 1, 1, 0, 0, 1, 500000, tzinfo=datetime.timezone.utc),
        ),
        ("date", datetime.date(1970, 1, 2)),
        ("duration", datetime.timedelta(seconds=90, microseconds=500)),
        # A struct: the same schema from the other side of the wire.
        ("struct_point", point),
        ("struct_person", person),
    ]


def main() -> int:
    fory = pyfory.Fory(xlang=True, ref=False, compatible=False)
    fory.register_type(Point, type_id=100)
    fory.register_type(Person, type_id=101)

    enum_fory = pyfory.Fory(xlang=True, ref=False, compatible=False)
    enum_fory.register_type(Color, type_id=200)

    rows = []
    for name, value in cases():
        rows.append((name, fory.serialize(value).hex()))
    rows.append(("enum", enum_fory.serialize(Color.GREEN).hex()))

    out = pathlib.Path(__file__).resolve().parent.parent / "src" / "fixtures_pyfory_test.mbt"
    lines = [
        "// Copyright 2026 Leo Cheng",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "// Generated by `scripts/interop.py` from pyfory %s. Do not edit." % pyfory.__version__,
        "//",
        "// One entry per class of message: the name the test reports, and the bytes",
        "// the Python implementation wrote for a value of that class. The file is a",
        "// test file rather than a library one, because fixtures are not an",
        "// interface: nothing outside the test suite should be able to reach them.",
        "// nothing outside the test suite should be able to reach them.",
        "",
        "///|",
        "let pyfory_fixtures : Array[(String, String)] = [",
    ]
    for name, text in rows:
        lines.append('  ("%s", "%s"),' % (name, text))
    lines.append("]")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print("wrote %s (%d fixtures)" % (out, len(rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
