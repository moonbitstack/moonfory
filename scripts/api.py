def write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="\n")


def main() -> int:
    if not MBTI.exists():
        print("missing %s; run `moon info` first" % MBTI.relative_to(ROOT), file=sys.stderr)
        return 1

    items = order(attach_items())
    if not items:
        print("no public items found", file=sys.stderr)
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    written = set()

    write(OUT / "index.html", index_page(items))
    written.add("index.html")

    for n, item in enumerate(items):
        prev = items[n - 1] if n > 0 else None
        nxt = items[n + 1] if n + 1 < len(items) else None
        write(OUT / item.url, item_page(item, items, prev, nxt))
        written.add(item.url)

    for stale in sorted(OUT.glob("*.html")):
        if stale.name in written:
            continue
        if MARK in stale.read_text(encoding="utf-8", errors="replace"):
            stale.unlink()

    methods = sum(len(i.methods) for i in items)
    print(
        "wrote %d pages and %d methods into %s"
        % (len(items) + 1, methods, OUT.relative_to(ROOT))
    )
    return 0


def attach_items() -> list[Item]:
    items = read_mbti(MBTI)
    attach(items, scan_sources())
    return items


if __name__ == "__main__":
    sys.exit(main())
