"""Write the API reference in `docs/api/` from the package itself.

Two files already say what the interface is, and neither one is written by
hand:

  * `src/pkg.generated.mbti` is what `moon info` prints. It is the public
    surface exactly — visibility, labels, defaults, generics, impls — and CI
    already fails when it is stale.
  * the `///` blocks in `src/*.mbt` are the prose, written beside the code
    they describe so that the two cannot drift apart.

This script joins them: one page per public item, an index that lists every
item by the file it lives in, and a source link on each page so a reader can
check the sentence against the code.

The output is deterministic on purpose — sorted, LF endings, no timestamps —
because CI regenerates it and requires `git diff` to be empty. Run it after
changing the interface or a doc comment:

    python3 scripts/api.py
"""

