DOC_DECL = {
    "struct": "struct",
    "enum": "enum",
    "suberror": "error",
}


def scan_sources() -> dict[str, dict]:
    """Map `kind:Owner::name` to its doc text, file and line.

    Keys are the same shape the `.mbti` reader builds, so the two can be
    joined without guessing at names.
    """
    found: dict[str, dict] = {}
    for path in sorted(SRC.glob("*.mbt")):
        if path.name.endswith("_test.mbt"):
            continue
        _scan_file(path, found)
    return found


def _scan_file(path: Path, found: dict[str, dict]) -> None:
    lines = path.read_text(encoding="utf-8").splitlines()
    buffer: list[str] = []
    member_buffer: list[str] = []
    owner: str | None = None  # the type whose body we are inside
    owner_kind = ""
    brace = 0
    i = 0

    def keep(buffer: list[str], key: str, line_no: int) -> None:
        text = "\n".join(buffer).strip("\n")
        if text.strip():
            found.setdefault(
                key, {"doc": text, "file": path.name, "line": line_no}
            )

    while i < len(lines):
        raw = lines[i]
        line = raw.strip()

        if line == "///|":
            buffer = []
            member_buffer = []
            i += 1
            continue

        if line.startswith("///"):
            text = line[3:]
            if text.startswith(" "):
                text = text[1:]
            (member_buffer if owner else buffer).append(text)
            i += 1
            continue

        if owner:
            if line.startswith("}"):
                brace -= line.count("}")
                if brace <= 0:
                    owner = None
                    owner_kind = ""
                    member_buffer = []
                i += 1
                continue
            if line and not line.startswith("//"):
                n = re.match(r"^(?:mut\s+)?(?:fn\s+)?([A-Za-z_]\w*)", line)
                if n:
                    key = {
                        "struct": "field",
                        "enum": "variant",
                        "error": "ctor",
                        "trait": "member",
                    }[owner_kind]
                    keep(member_buffer, "%s:%s::%s" % (key, owner, n.group(1)), i + 1)
                    member_buffer = []
                brace += line.count("{") - line.count("}")
                i += 1
                continue
            i += 1
            continue

        # At the top level: a declaration closes the doc block in front of it.
        m = re.match(r"^pub(?:\(all\))?\s+(struct|enum|suberror)\s+([A-Za-z_]\w*)", line)
        if m:
            owner_kind = DOC_DECL[m.group(1)]
            keep(buffer, "%s:%s" % (owner_kind, m.group(2)), i + 1)
            buffer = []
            member_buffer = []
            owner = m.group(2)
            brace = line.count("{") - line.count("}")
            i += 1
            continue

        m = re.match(r"^pub\s+trait\s+([A-Za-z_]\w*)", line)
        if m:
            keep(buffer, "trait:%s" % m.group(1), i + 1)
            buffer = []
            member_buffer = []
            owner = m.group(1)
            owner_kind = "trait"
            brace = line.count("{") - line.count("}")
            i += 1
            continue

        m = re.match(
            r"^pub\s+fn(?:\[[^\]]*\])?\s+([A-Za-z_]\w*)(?:::([A-Za-z_]\w*))?", line
        )
        if m:
            if m.group(2):
                keep(buffer, "fn:%s::%s" % (m.group(1), m.group(2)), i + 1)
            else:
                keep(buffer, "fn:%s" % m.group(1), i + 1)
            buffer = []
            i += 1
            continue

        m = re.match(r"^pub\s+let\s+([A-Za-z_]\w*)", line)
        if m:
            keep(buffer, "value:%s" % m.group(1), i + 1)
            buffer = []
            i += 1
            continue

        if line.startswith("pub"):
            buffer = []
        i += 1


