def rail_links(items: list[Item], current: Item, category: str) -> str:
    """The rail: the current item's category, then the way back to the index.

    Only the category, not all forty-two: an entry page should not open with
    the whole contents list beside it, and the item is one of a handful that
    a reader is likely to move between.
    """
    out = ['<div class="grp">%s</div>' % esc(category)]
    for item in items:
        if item.category == category:
            out.append(_rail_a(item, current))
    out.append('<div class="grp">All items</div>')
    out.append('<a href="index.html">API index</a>')
    return "\n        ".join(out)


def _rail_a(item: Item, current: Item) -> str:
    if item is current:
        return '<a href="%s" aria-current="page">%s</a>' % (item.url, esc(item.name))
    return '<a href="%s">%s</a>' % (item.url, esc(item.name))


def source_link(item: Item, prefix: str = "") -> str:
    if not item.file or not item.line:
        return ""
    href = "%s/blob/%s/src/%s#L%d" % (REPO, BRANCH, item.file, item.line)
    return '<a href="%s">%s:%d</a>' % (href, item.file, item.line)


def item_page(item: Item, items: list[Item], prev: Item | None, nxt: Item | None) -> str:
    parts: list[str] = []
    parts.append('<p class="eyebrow">API · %s</p>' % item.label)
    parts.append("<h2>%s</h2>" % esc(item.name))
    if item.file:
        parts.append(
            '<p class="api-meta">%s · defined at %s</p>'
            % (esc(item.category), source_link(item))
        )
    else:
        parts.append('<p class="api-meta">%s</p>' % esc(item.category))

    parts.append(decl_block(item))
    if item.doc:
        parts.append(blocks(item.doc))

    if item.members:
        parts.append("<h3>%s</h3>" % _member_heading(item.kind))
        if any(m.doc for m in item.members):
            parts.append('<table class="api-table">')
            parts.append(
                "<tr><th>%s</th><th>Meaning</th></tr>" % _member_column(item.kind)
            )
            for m in item.members:
                parts.append(
                    "<tr><td>%s</td><td>%s</td></tr>"
                    % (_member_name(item.kind, m), blocks(m.doc))
                )
            parts.append("</table>")
        else:
            # Nothing to explain one by one: the enumeration is the list, and
            # a two-column table with an empty side reads as a hole.
            parts.append(
                '<p class="api-variants">%s</p>'
                % " ".join(
                    "<code>%s</code>" % esc(m.name) for m in item.members
                )
            )

    if item.methods:
        parts.append("<h3>Methods</h3>")
        for m in item.methods:
            parts.append('<div class="api-method" id="%s">' % esc(m.name))
            parts.append(
                '<h4><a class="anchor" href="#%s">%s</a></h4>' % (esc(m.name), esc(m.name))
            )
            parts.append(sig_block(_drop_pub(m.sig), "sig"))
            if m.doc:
                parts.append(blocks(m.doc))
            parts.append("</div>")

    if item.derives or item.impls:
        parts.append(
            "<h3>%s</h3>" % ("Implementors" if item.kind == "trait" else "Built in")
        )
        chips = []
        for d in item.derives:
            chips.append("<code>%s</code>" % esc(d))
        chips_html = " ".join(chips) if chips else ""
        if chips_html:
            parts.append(
                '<p class="api-impls">derives %s</p>' % chips_html
            )
        for impl in item.impls:
            parts.append('<p class="api-impls"><code>%s</code></p>' % esc(impl))

    parts.append(
        '<p class="api-src">Generated from <code>src/pkg.generated.mbti</code> '
        "and the doc comments beside this declaration.</p>"
    )

    pager = ['<nav class="pager" aria-label="Previous and next">']
    if prev is not None:
        pager.append(
            '<a class="prev" href="%s"><span>previous</span>%s</a>'
            % (prev.url, esc(prev.name))
        )
    else:
        pager.append('<span class="prev"></span>')
    if nxt is not None:
        pager.append(
            '<a class="next" href="%s"><span>next</span>%s</a>'
            % (nxt.url, esc(nxt.name))
        )
    else:
        pager.append('<span class="next"></span>')
    pager.append("</nav>")
    parts.append("\n        ".join(pager))

    body = """    <main class="docs">
      <aside class="rail" aria-label="Contents">
        %s
      </aside>

      <article class="article">
        %s
      </article>
    </main>""" % (
        rail_links(items, item, item.category),
        "\n        ".join(parts),
    )

    title = "%s %s — moonfory API" % (item.label, item.name)
    desc = summary(item.doc) or "The public %s %s of moonfory." % (item.label, item.name)
    return shell(title, desc, "../", body)


def _member_heading(kind: str) -> str:
    return {
        "struct": "Fields",
        "enum": "Variants",
        "error": "Constructors",
        "trait": "Required methods",
    }.get(kind, "Members")


def _member_column(kind: str) -> str:
    return {
        "struct": "Field",
        "enum": "Variant",
        "error": "Constructor",
        "trait": "Method",
    }.get(kind, "Member")


def _member_name(kind: str, m: Member) -> str:
    return "<code>%s</code>" % esc(m.sig or m.name)


def _drop_pub(sig: str) -> str:
    head = sig.split("\n")[0]
    rest = "\n".join(sig.split("\n")[1:])
    head = re.sub(r"^pub\s+", "", head)
    return head + ("\n" + rest if rest else "")


def index_page(items: list[Item]) -> str:
    total = len(items)
    kinds: dict[str, int] = {}
    for item in items:
        kinds[item.label] = kinds.get(item.label, 0) + 1
    plural = {
        "fn": ("function", "functions"),
        "let": ("value", "values"),
        "struct": ("struct", "structs"),
        "enum": ("enum", "enums"),
        "error": ("error", "errors"),
        "trait": ("trait", "traits"),
    }
    tally = ", ".join(
        "%d %s" % (kinds[k], plural[k][0] if kinds[k] == 1 else plural[k][1])
        for k in ("fn", "let", "struct", "enum", "error", "trait")
        if k in kinds
    )
    methods = sum(len(i.methods) for i in items)

    parts: list[str] = []
    parts.append('<p class="eyebrow">Reference</p>')
    parts.append("<h2>Every public item, one page each.</h2>")
    parts.append(
        '<p class="lede-2">%d items: %s, and %d methods documented on the pages '
        "of the types they belong to. The signatures and the prose are both "
        "taken from the package — <code>moon info</code> for the first, the "
        "<code>///</code> comments beside each declaration for the second — so "
        "a page here cannot describe a function that no longer exists.</p>"
        % (total, tally, methods)
    )

    for cat in CATEGORY_ORDER:
        group = [i for i in items if i.category == cat]
        if not group:
            continue
        parts.append('<h3 class="api-group">%s</h3>' % esc(cat))
        parts.append('<table class="api-table">')
        parts.append("<tr><th>Item</th><th>Kind</th><th>Summary</th></tr>")
        for item in group:
            parts.append(
                '<tr><td><a href="%s">%s</a></td><td><span class="api-kind">%s</span></td>'
                "<td>%s</td></tr>"
                % (
                    item.url,
                    esc(item.name),
                    item.label,
                    inline(summary(item.doc)),
                )
            )
        parts.append("</table>")

    parts.append('<hr class="rule" />')
    parts.append(
        '<div class="note"><b>Regenerated, not written.</b> '
        "<code>python3 scripts/api.py</code> writes this directory from "
        "<code>src/pkg.generated.mbti</code> and <code>src/*.mbt</code>; CI runs "
        "it and refuses a diff. A method links to its type's page under an "
        "anchor rather than to a page of its own, because a method is only "
        "readable next to the type it hangs off.</div>"
    )

    # No rail: this page is the contents, and repeating all forty-two links
    # beside the list of forty-two links is what a phone would show first.
    body = """    <main class="docs docs--single">
      <article class="article">
        %s
      </article>
    </main>""" % ("\n        ".join(parts))
    return shell(
        "API reference — moonfory",
        "Every public item of moonfory, one page each, generated from the "
        "interface and the doc comments.",
        "../",
        body,
    )


