def attach(items: list[Item], docs: dict[str, dict]) -> None:
    def doc_of(key: str) -> dict:
        return docs.get(key, {})

    for item in items:
        key = "%s:%s" % (item.kind, item.name)
        found = doc_of(key)
        item.doc = found.get("doc", "")
        item.file = found.get("file", "")
        item.line = found.get("line", 0)
        item.category = category_of(item.file)
        for m in item.members:
            sub = {
                "struct": "field",
                "enum": "variant",
                "error": "ctor",
                "trait": "member",
            }[item.kind]
            m.doc = doc_of("%s:%s::%s" % (sub, item.name, m.name)).get("doc", "")
        for m in item.methods:
            m.doc = doc_of("fn:%s::%s" % (item.name, m.name)).get("doc", "")


def category_of(file: str) -> str:
    for name, label in CATEGORIES:
        if name == file:
            return label
    return "Elsewhere"


def order(items: list[Item]) -> list[Item]:
    def key(item: Item):
        return (CATEGORY_ORDER.index(item.category), item.name.lower(), item.name)

    return sorted(items, key=key)


# --------------------------------------------------------------------------
# rendering


def esc(text: str) -> str:
    return html.escape(text, quote=False)


def attr(text: str) -> str:
    """For a value inside a quoted attribute: a `"` in a doc comment would
    otherwise end the `content=` early and take the rest of the tag with it.

    Only the double quote is escaped. `html.escape` would also turn every
    possessive apostrophe into `&#x27;` — correct, and unreadable in a file
    that anyone might open to see what a page says.
    """
    return html.escape(text, quote=True).replace("&#x27;", "'")


def inline(text: str) -> str:
    out = esc(text)
    out = re.sub(r"`([^`]+)`", lambda m: "<code>%s</code>" % m.group(1), out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", out)
    out = re.sub(
        r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', out
    )
    return out


def blocks(text: str) -> str:
    """Blank-line separated paragraphs, with `- ` runs becoming a list."""
    if not text.strip():
        return ""
    out = []
    for para in re.split(r"\n\s*\n", text.strip()):
        lines = [l.strip() for l in para.splitlines() if l.strip()]
        if not lines:
            continue
        if all(l.startswith("- ") for l in lines):
            out.append(
                "<ul>%s</ul>" % "".join("<li>%s</li>" % inline(l[2:]) for l in lines)
            )
        else:
            out.append("<p>%s</p>" % inline(" ".join(lines)))
    return "\n        ".join(out)


def summary(text: str, limit: int = 220) -> str:
    """The first sentence, whole where it fits.

    A truncated sentence is worse than a long one — "for a buffer that already
    hold…" tells a reader nothing — so the cut only happens past a word
    boundary, and only when the sentence is far too long for a table cell.
    """
    flat = " ".join(text.replace("`", "").replace("**", "").split())
    if not flat:
        return ""
    m = re.match(r"(.+?[.!?])(?:\s|$)", flat)
    one = m.group(1) if m else flat
    if len(one) > limit:
        cut = one[:limit].rsplit(" ", 1)[0].rstrip(" ,;:")
        one = cut + "…"
    return one


def decl_block(item: Item) -> str:
    """The declaration, whole where it fits.

    An enumeration with fifty-six variants prints as a thousand pixels of
    names that the Variants section lists again, right below, with the prose
    attached. Past a screen's worth the block becomes an excerpt and says how
    many were left out — and loses its copy button, because copying half a
    declaration without noticing is worse than not offering it.
    """
    lines = item.sig.split("\n")
    body = lines[1:-1] if len(lines) > 2 else []
    if len(body) <= 16:
        return sig_block(item.sig, "code")
    kept = 14
    text = "\n".join([lines[0]] + body[:kept] + ["  …"] + [lines[-1]])
    return (
        sig_block(text, "sig")
        + '<p class="api-more">%d more, listed under %s below.</p>'
        % (len(body) - kept, _member_heading(item.kind).lower())
    )


def sig_block(sig: str, cls: str = "code") -> str:
    """A block of MoonBit.

    Only the page's own declaration gets a copy button: a method signature is
    two lines and is read in place, so a control hovering over every one of
    them would be furniture, not help.
    """
    if cls == "code":
        # `wrap`: a declaration with ten optional arguments is the entry
        # itself, so it wraps rather than hides its tail behind a scroll.
        return (
            '<div class="code wrap"><button class="copy" data-copy>copy</button>'
            "<pre>%s</pre></div>" % esc(sig)
        )
    return '<div class="%s"><pre>%s</pre></div>' % (cls, esc(sig))


def nav(root: str, current: str) -> str:
    links = [
        ("index.html", "Home"),
        ("docs.html", "Docs"),
        ("examples.html", "Examples"),
        ("api/index.html", "API"),
    ]
    out = []
    for href, label in links:
        if label == current:
            out.append('<a href="%s%s" aria-current="page">%s</a>' % (root, href, label))
        else:
            out.append('<a href="%s%s">%s</a>' % (root, href, label))
    out.append('<a href="%s">GitHub</a>' % REPO)
    return "\n        ".join(out)


