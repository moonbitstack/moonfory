// Write the Go half of the interop fixtures.
//
// Run this by hand, from this directory:
//
//	cd scripts && go run .
//
// It writes `src/fixtures_go_test.mbt`: one entry per class of message, holding
// the bytes Go's `fory` wrote for a value of that class. The file is checked in
// and the tests read it, so CI never runs this program and never needs Go.
//
// Go is the peer for the shapes Python cannot write — a cycle, above all: its
// serializer recurses and crashes on a struct that contains itself, while Go
// writes one and reads one.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"time"

	"github.com/apache/fory/go/fory"
)

// Point is the schema the Python fixtures also call Point: same name, same user
// type ID, same fields, which is what makes the two files comparable.
type Point struct {
	X int32
	Y int32
}

// Node points at itself: the one shape only Go can write.
type Node struct {
	Val  int32
	Next *Node
}

type fixture struct {
	name  string
	bytes []byte
}

func main() {
	xlang := fory.NewFory(fory.WithXlang(true), fory.WithTrackRef(false), fory.WithCompatible(false))
	must(xlang.RegisterStruct(&Point{}, 100))

	cycling := fory.NewFory(fory.WithXlang(true), fory.WithTrackRef(true), fory.WithCompatible(false))
	must(cycling.RegisterStruct(&Node{}, 300))

	node := &Node{Val: 1}
	node.Next = node

	cases := []struct {
		name  string
		write func() ([]byte, error)
	}{
		{"bool", func() ([]byte, error) { return xlang.Serialize(true) }},
		{"float64", func() ([]byte, error) { return xlang.Serialize(1.5) }},
		{"string_utf8", func() ([]byte, error) { return xlang.Serialize("世界") }},
		{"binary", func() ([]byte, error) { return xlang.Serialize([]byte("ab")) }},
		{"int32_array", func() ([]byte, error) { return xlang.Serialize([]int32{1, 2, 3}) }},
		{"struct_point", func() ([]byte, error) { return xlang.Serialize(&Point{1, 2}) }},
		{"timestamp", func() ([]byte, error) {
			return xlang.Serialize(time.Unix(1, 500000000).UTC())
		}},
		{"cycle_node", func() ([]byte, error) { return cycling.Serialize(node) }},
	}

	fixtures := make([]fixture, 0, len(cases))
	for _, one := range cases {
		bytes, err := one.write()
		if err != nil {
			fmt.Fprintf(os.Stderr, "%s: %v\n", one.name, err)
			os.Exit(1)
		}
		// The buffer behind the slice is the serializer's and is reused, so the
		// bytes are copied out before the next value overwrites them.
		fixtures = append(fixtures, fixture{one.name, append([]byte(nil), bytes...)})
	}

	out := filepath.Join("..", "src", "fixtures_go_test.mbt")
	body := `// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by ` + "`scripts/interop.go`" + ` from Go's fory. Do not edit.
//
// One entry per class of message: the name the test reports, and the bytes the
// Go implementation wrote for a value of that class. A test file rather than a
// library one, because fixtures are not an interface.
//
// ` + "`cycle_node`" + ` is the one fixture no other implementation can produce: Python's
// serializer recurses on a struct that contains itself.

///|
let go_fixtures : Array[(String, String)] = [
`
	for _, f := range fixtures {
		body += fmt.Sprintf("\t(\"%s\", \"%x\"),\n", f.name, f.bytes)
	}
	body += "]\n"

	if err := os.WriteFile(out, []byte(body), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s (%d fixtures)\n", out, len(fixtures))
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
